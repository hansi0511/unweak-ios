import sys
sys.path.insert(0, sys.argv[1])
from anims import *
def n(v):
    r = round(v, 2)
    return str(int(r)) if r == int(r) else f"{r:g}"
def pnt(p): return f"p({n(p[0])}, {n(p[1])})"
def limb(s):
    if s[0] == 'a': return f".angles({n(s[1])}, {n(s[2])})"
    return f".pinned({pnt(s[1])}, .{'positive' if s[2] > 0 else 'negative'})"
def pose(p):
    return (f"BodyPose(hip: {pnt(p['hip'])}, torso: {n(p['torso'])}, neck: {n(p['neck'])},\n"
            f"                     arms: [{', '.join(limb(a) for a in p['arms'])}],\n"
            f"                     legs: [{', '.join(limb(l) for l in p['legs'])}])")
out = ["// Generated by tools/sticky/gen.py from the key poses in tools/sticky/anims.py (checked visually and for",
       "// bone lengths, contact points and canvas bounds). Edit values with care:",
       "// the tests in StickyBodyTests check the same constraints.",
       "", "import CoreGraphics", "",
       "private func p(_ x: CGFloat, _ y: CGFloat) -> CGPoint { CGPoint(x: x, y: y) }", "",
       "private func line(_ a: CGPoint, _ b: CGPoint, opacity: Double = 1) -> StickySegment {",
       "    StickySegment(from: a, to: b, width: StickyStyle.apparatusWidth, opacity: opacity)",
       "}", "",
       "/// Floor line, drawn faintly.",
       "private let floorLine = line(p(10, 158.5), p(190, 158.5), opacity: 0.35)", "",
       "extension BodyAnimation {"]
for name, A in ANIMS.items():
    app = []
    for a, b in A['app']:
        app.append("floorLine" if (a, b) == ((10, FLOOR+1.5), (190, FLOOR+1.5)) else f"line({pnt(a)}, {pnt(b)})")
    out.append(f"    static let {name} = BodyAnimation(")
    out.append(f"        canvas: CGSize(width: {A['canvas'][0]}, height: {A['canvas'][1]}),")
    out.append(f"        duration: {n(A['dur'])},")
    out.append(f"        endPoseProgress: {n(A['end'])},")
    out.append(f"        apparatus: [{', '.join(app)}],")
    out.append("        keys: [")
    for t, p in A['keys']:
        out.append(f"            Key(time: {n(t)}, pose: {pose(p)}),")
    out.append("        ]")
    out.append("    )")
    out.append("")
out[-1] = "}"
print("\n".join(out))
